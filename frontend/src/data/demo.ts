export function buildTasks(
  completedCount: number,
  inProgress?: number,
): TaskItem[] {
  return TASK_NAMES.map((name, index) => {
    const number = index + 1;
    let status: TaskItem["status"] = "pending";
    if (number <= completedCount) status = "completed";
    else if (number === inProgress) status = "in_progress";
    else if (number === completedCount + 1 && !inProgress) status = "eligible";
    return {
      number,
      name,
      status,
      ...(status === "completed"
        ? {
            completedAt: `2026-10-${String(Math.max(1, 20 - (completedCount - number))).padStart(2, "0")}T15:30:00Z`,
          }
        : {}),
      ...(status === "eligible" || status === "in_progress"
        ? { dueDate: "2026-10-26" }
        : {}),
    };
  });
}

